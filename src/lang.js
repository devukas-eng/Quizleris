let currentLanguage = 'lt'; // Default to Lithuanian
// Initialize language from localStorage or default
export function initLanguage() {
    const saved = localStorage.getItem('quiz_language');
    if (saved && (saved === 'lt' || saved === 'en')) {
        currentLanguage = saved;
    }
}
// Get current language
export function getLanguage() {
    return currentLanguage;
}

/** A date in the page's language, as `options` asks; empty when there is no valid date. */
export function localDate(value, options) {
    const date = value ? new Date(value) : null;
    if (!date || Number.isNaN(date.getTime())) return "";
    return date.toLocaleString(currentLanguage === "lt" ? "lt-LT" : "en-GB", options);
}
// Set language and persist
export function setLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('quiz_language', lang);
}
// Translate a key
export function t(key) {
    return translations[currentLanguage][key] || key;
}
// Update all translatable elements in the DOM
export function updatePageLanguage() {
    // Browsers read this to tell what language the page is in
    document.documentElement.lang = currentLanguage;

    // Save current values of all select elements to prevent resets during option updates
    const selectStates = new Map();
    document.querySelectorAll('select').forEach(select => {
        selectStates.set(select, select.value);
    });

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n')?.trim();
        if (key) {
            el.textContent = t(key);
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder')?.trim();
        if (key && el instanceof HTMLInputElement) {
            el.placeholder = t(key);
        }
    });
    // Icon-only buttons: translate the tooltip and the screen-reader name, keep the icon
    document.querySelectorAll('[data-i18n-label]').forEach(el => {
        const key = el.getAttribute('data-i18n-label')?.trim();
        if (key) {
            el.title = t(key);
            el.setAttribute('aria-label', t(key));
        }
    });

    // Restore saved select values
    selectStates.forEach((savedValue, select) => {
        select.value = savedValue;
    });
}
